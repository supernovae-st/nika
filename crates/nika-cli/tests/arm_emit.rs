//! `nika arm --emit` end-to-end (W3 · « LE PONT », the OS bridge): a
//! tempdir project, the real binary, HOME redirected into the tempdir
//! (the write tests never touch a developer's `LaunchAgents`), and the
//! machine zone read through the same jiff call the verb makes.
//!
//! The pinned laws: print by default, nothing written without
//! `--write` · the units land where the OS reads them · D7 (an env file
//! rides by PATH, a secret VALUE never crosses) · D2 (every unit calls
//! `arm fire`, never `run`) · D10 (a foreign zone wakes launchd at the
//! machine hours its slots fall on, and rides systemd's `OnCalendar=`).

use std::io::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

fn bin() -> Command {
    let mut cmd = Command::new(env!("CARGO_BIN_EXE_nika"));
    cmd.stdin(std::process::Stdio::null());
    cmd
}

/// The machine's IANA zone — the same read the verb does. A zoneless
/// machine cannot run this suite (the verb refuses it too, by design).
fn machine_zone() -> String {
    jiff::tz::TimeZone::system()
        .iana_name()
        .expect("cette machine n'a pas de fuseau IANA nommé — le verbe le refuserait aussi")
        .to_owned()
}

/// A beat's workflow that is READY to arm: no input to bind, no model to
/// price (emit never runs it, but it refuses a beat that could not run).
const READY_WORKFLOW: &str = "nika: beat\npermits:\n  exec: [\"echo\"]\ntasks:\n  hi:\n    exec: { command: [\"echo\", \"ok\"] }\n";

/// A tempdir project: the registry and each workflow it names, READY.
fn project(tag: &str, registry: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("nika-arm-emit-{tag}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).expect("project dir");
    let mut f = std::fs::File::create(dir.join("nika.yaml")).expect("registry file");
    f.write_all(registry.as_bytes()).expect("registry body");
    for workflow in registry
        .lines()
        .filter_map(|line| line.trim().strip_prefix("- workflow: "))
    {
        let file = dir.join(workflow);
        std::fs::create_dir_all(file.parent().expect("workflow dir")).expect("workflow dir");
        std::fs::write(&file, READY_WORKFLOW).expect("workflow");
    }
    dir
}

/// A redirected HOME inside the tempdir.
fn home(dir: &Path) -> PathBuf {
    let home = dir.join("home");
    std::fs::create_dir_all(&home).expect("home dir");
    home
}

/// A one-beat registry in the machine's zone.
fn registry_in(zone: &str) -> String {
    format!(
        "nika: proj\narm:\n  - workflow: workflows/doctor.nika\n    cadence: \"TZ={zone} 0 3 * * *\"\n    plafond: 0.05\n    manqué: sauter\n"
    )
}

/// Run `nika-cli arm …` inside the project with HOME redirected.
fn arm(dir: &Path, home: &Path, args: &[&str]) -> std::process::Output {
    bin()
        .args(args)
        .current_dir(dir)
        .env("HOME", home)
        .output()
        .expect("spawn arm")
}

/// The unit label `nika arm --emit` gives `label` in the project at `dir`:
/// the key is the start of the canonical root's fingerprint.
fn unit(dir: &Path, label: &str) -> String {
    let fingerprint =
        nika_runtime::project_root_fingerprint(dir).expect("the project root resolves");
    nika_cadence::emit::beat_unit(&nika_cadence::emit::project_key(&fingerprint), label)
}

/// A unit an older engine wrote: the name without the project key, the
/// GENERATED header naming `project_file`.
fn legacy_plist(project_file: &Path, label: &str) -> String {
    format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!-- nika arm · GENERATED from {} · beat {label} · do not hand-edit · regenerated by nika arm emit launchd -->\n<plist version=\"1.0\"><dict><key>Label</key><string>nika.arm.{label}</string></dict></plist>\n",
        project_file.display()
    )
}

/// `--beat <label>` writes that beat's unit alone: another beat of the project, even one that
/// could not arm, keeps no unit and refuses nothing (D1: a schedule kept declared only gets no
/// unit when another one is installed). An unknown label refuses with the labels.
#[test]
fn emit_beat_writes_only_that_beats_unit() {
    let zone = machine_zone();
    let registry = format!(
        "nika: proj\narm:\n  - workflow: workflows/doctor.nika\n    cadence: \"TZ={zone} 0 3 * * *\"\n    plafond: 0.05\n    manqué: sauter\n  - workflow: workflows/digest.nika\n    cadence: \"TZ={zone} 0 9 * * *\"\n    plafond: 0.05\n    manqué: sauter\n"
    );
    let dir = project("one-beat", &registry);
    let home = home(&dir);
    // The other beat could not arm: its workflow is missing.
    std::fs::remove_file(dir.join("workflows/digest.nika")).expect("unready digest");
    let out = arm(
        &dir,
        &home,
        &["arm", "--emit", "launchd", "--write", "--beat", "doctor"],
    );
    let stdout = String::from_utf8_lossy(&out.stdout);
    assert_eq!(
        out.status.code(),
        Some(0),
        "{stdout} {}",
        String::from_utf8_lossy(&out.stderr)
    );
    let agents = home.join("Library/LaunchAgents");
    assert!(
        agents
            .join(format!("{}.plist", unit(&dir, "doctor")))
            .is_file(),
        "{stdout}"
    );
    assert!(
        !agents
            .join(format!("{}.plist", unit(&dir, "digest")))
            .exists(),
        "{stdout}"
    );
    let unknown = arm(&dir, &home, &["arm", "--emit", "launchd", "--beat", "nope"]);
    let said = String::from_utf8_lossy(&unknown.stdout);
    assert_ne!(unknown.status.code(), Some(0));
    assert!(
        said.contains("aucun beat `nope`") && said.contains("doctor, digest"),
        "{said}"
    );
    let _ = std::fs::remove_dir_all(&dir);
}

/// A beat that reads a provider key as a run does: the variable passes to its one step through
/// `permits.env`, and the step prints it (the run's trace keeps the output).
const KEYED_WORKFLOW: &str = "nika: keyed\npermits:\n  exec: [\"printenv\"]\n  env: [\"NIKA_QA_DOTENV_KEY\"]\ntasks:\n  key:\n    exec: { command: [\"printenv\", \"NIKA_QA_DOTENV_KEY\"] }\n";

/// The `ProgramArguments` of a printed plist, unescaped, in order.
fn program_arguments(plist: &str) -> Vec<String> {
    let start = plist.find("<key>ProgramArguments</key>").expect("an argv");
    let argv = &plist[start..];
    let end = argv.find("</array>").expect("the argv ends");
    (argv[..end].lines().map(str::trim))
        .filter_map(|line| line.strip_prefix("<string>")?.strip_suffix("</string>"))
        .map(|arg| {
            arg.replace("&apos;", "'")
                .replace("&quot;", "\"")
                .replace("&lt;", "<")
                .replace("&gt;", ">")
                .replace("&amp;", "&")
        })
        .collect()
}

/// NIK-198 · an env file of plain `KEY=value` lines, as a dotenv holds them, reaches the run a
/// launchd unit fires. The unit hands the file to `nika arm fire --env-file`, which reads it
/// itself: no shell sources it (supernovae-1c, 2026-10-17: the sourced keys never reached the
/// firer, and every scheduled API run failed). The unit's own argv runs under launchd's
/// environment (HOME, USER and the system PATH alone), the injected clock aside.
#[test]
fn a_dotenv_without_export_reaches_the_run_a_launchd_unit_fires() {
    let zone = machine_zone();
    let dir = project("dotenv", &registry_in(&zone));
    let home = home(&dir);
    std::fs::write(dir.join("workflows/doctor.nika"), KEYED_WORKFLOW).expect("keyed beat");
    let keys = dir.join("keys.env");
    std::fs::write(&keys, "# keys\nNIKA_QA_DOTENV_KEY=from-the-file\n").expect("dotenv");
    let keys_arg = keys.to_str().expect("utf-8");
    let out = arm(
        &dir,
        &home,
        &["arm", "--emit", "launchd", "--env-file", keys_arg],
    );
    let stdout = String::from_utf8_lossy(&out.stdout);
    assert_eq!(out.status.code(), Some(0), "{stdout}");
    let argv = program_arguments(&stdout);
    assert!(
        !argv
            .iter()
            .any(|arg| arg == "/bin/sh" || arg.contains(". ")),
        "no shell sources the file: {argv:?}"
    );
    assert_eq!(argv[1..4], ["arm", "fire", "doctor"], "{argv:?}");
    let at = (argv.iter().position(|arg| arg == "--env-file")).expect("the firer gets the file");
    assert_eq!(argv.get(at + 1).map(String::as_str), Some(keys_arg));
    let slot = jiff::civil::date(2026, 8, 19)
        .at(3, 2, 0, 0)
        .in_tz(&zone)
        .expect("a slot in the machine zone")
        .to_string();
    let fired = Command::new(&argv[0])
        .args(&argv[1..])
        .args(["--now", &slot])
        .current_dir(&dir)
        .stdin(std::process::Stdio::null())
        .env_clear()
        .env("HOME", &home)
        .env("USER", "nika-qa")
        .env("PATH", "/usr/bin:/bin")
        .env("NIKA_KEYCHAIN", "off")
        .output()
        .expect("the unit's own argv");
    let line = String::from_utf8_lossy(&fired.stdout);
    let stderr = String::from_utf8_lossy(&fired.stderr);
    assert_eq!(fired.status.code(), Some(0), "{line} · {stderr}");
    assert!(
        line.starts_with("fired doctor · slot "),
        "{line} · {stderr}"
    );
    assert!(
        !line.contains("from-the-file"),
        "the firer never prints a value: {line}"
    );
    let last = std::fs::read_to_string(dir.join(".nika/arm/doctor/last.json")).expect("last.json");
    let last: serde_json::Value = serde_json::from_str(&last).expect("last.json is JSON");
    let trace = dir.join(last["trace"].as_str().expect("the fire's trace"));
    let journal = std::fs::read_to_string(trace).expect("the trace");
    assert!(
        journal.contains("from-the-file"),
        "the fired run read the key from the file"
    );
    let _ = std::fs::remove_dir_all(&dir);
}

