/// The month end and the anchored interval on the real systemd: the
/// emitted pairs verify, and the month end's `OnCalendar=` (read back from
/// the timer the verb wrote) elapses on the last day of each month by
/// systemd's own calendar, never on a 28-31 guess. Skipped, by name, when
/// the tool is absent.
#[cfg(target_os = "linux")]
#[test]
fn systemd_speaks_the_month_end_and_the_interval_or_skips_absent() {
    if Command::new("systemd-analyze")
        .arg("--version")
        .output()
        .is_err()
    {
        eprintln!(
            "SKIP systemd_speaks_the_month_end_and_the_interval_or_skips_absent · systemd-analyze absent"
        );
        return;
    }
    let registry = concat!(
        "nika: proj\narm:\n",
        "  - workflow: workflows/close.nika\n    cadence: \"TZ=UTC 0 9 L * *\"\n",
        "    plafond: 0.05\n    manqué: sauter\n",
        "  - workflow: workflows/sprint.nika\n",
        "    cadence: \"TZ=UTC every 2 weeks from 2026-10-05 09:00\"\n",
        "    plafond: 0.05\n    manqué: sauter\n",
    );
    let dir = project("forms", registry);
    let home = home(&dir);
    let out_dir = dir.join("units");
    let out = arm(
        &dir,
        &home,
        &[
            "arm",
            "--emit",
            "systemd",
            "--write",
            "--out",
            out_dir.to_str().expect("utf8"),
        ],
    );
    assert_eq!(
        out.status.code(),
        Some(0),
        "stderr: {}",
        String::from_utf8_lossy(&out.stderr)
    );
    let mut entries: Vec<PathBuf> = std::fs::read_dir(&out_dir)
        .expect("units dir")
        .filter_map(std::result::Result::ok)
        .map(|e| e.path())
        .collect();
    entries.sort();
    assert_eq!(entries.len(), 4, "two timer/service pairs");
    let verify = Command::new("systemd-analyze")
        .arg("verify")
        .args(&entries)
        .output()
        .expect("systemd-analyze verify");
    assert!(
        verify.status.success(),
        "systemd-analyze verify: {}{}",
        String::from_utf8_lossy(&verify.stdout),
        String::from_utf8_lossy(&verify.stderr)
    );
    let timer = std::fs::read_to_string(out_dir.join(format!("{}.timer", unit(&dir, "close"))))
        .expect("timer");
    let calendar = timer
        .lines()
        .find_map(|line| line.strip_prefix("OnCalendar="))
        .expect("OnCalendar=");
    assert_eq!(calendar, "*-*~01 09:00:00 UTC");
    let elapses = Command::new("systemd-analyze")
        .args(["calendar", "--iterations=13", calendar])
        .output()
        .expect("systemd-analyze calendar");
    let text = String::from_utf8_lossy(&elapses.stdout);
    let days: Vec<jiff::civil::Date> = text
        .lines()
        // Older systemd-analyze prints « Iter. #N », newer ones « Iteration #N » (the CI runner).
        .filter(|line| {
            line.contains("Next elapse:")
                || line.contains("Iter. #")
                || line.contains("Iteration #")
        })
        .filter_map(|line| line.split_whitespace().find_map(|w| w.parse().ok()))
        .collect();
    assert_eq!(days.len(), 13, "thirteen elapses: {text}");
    for day in days {
        assert_eq!(
            day.day(),
            day.days_in_month(),
            "{day} is not a month end: {text}"
        );
    }
}

// ── Orphan units: the registry is the truth, `--write` syncs the units ──

/// A two-beat registry in the machine's zone: `doctor` and `report`.
fn two_beats_in(zone: &str) -> String {
    format!(
        "{}  - workflow: workflows/report.nika\n    cadence: \"TZ={zone} 0 4 * * *\"\n    plafond: 0.05\n    manqué: sauter\n",
        registry_in(zone)
    )
}

/// A beat removed from `nika.yaml` left a unit that would wake it forever:
/// a dry emit lists it, the next `--emit --write` retires it (its unload
/// said, its file removed), and the beat still declared keeps its unit.
#[test]
fn emit_write_retires_the_unit_of_a_beat_no_longer_declared() {
    let zone = machine_zone();
    let dir = project("orphan", &two_beats_in(&zone));
    let home = home(&dir);
    let out = arm(&dir, &home, &["arm", "--emit", "launchd", "--write"]);
    assert_eq!(out.status.code(), Some(0), "{out:?}");
    let agents = home.join("Library/LaunchAgents");
    let doctor = agents.join(format!("{}.plist", unit(&dir, "doctor")));
    let report = agents.join(format!("{}.plist", unit(&dir, "report")));
    assert!(doctor.exists() && report.exists(), "both beats armed");
    std::fs::write(dir.join("nika.yaml"), registry_in(&zone)).expect("report removed");

    let dry = arm(&dir, &home, &["arm", "--emit", "launchd"]);
    let listed = String::from_utf8_lossy(&dry.stdout);
    assert!(
        listed.contains(&format!(
            "`--write` retirerait {} (plus de beat `report` armé)",
            unit(&dir, "report")
        )),
        "{listed}"
    );
    assert!(report.exists(), "a dry emit removes nothing");

    let out = arm(&dir, &home, &["arm", "--emit", "launchd", "--write"]);
    let stdout = String::from_utf8_lossy(&out.stdout);
    assert_eq!(out.status.code(), Some(0), "{stdout}");
    assert!(
        stdout.contains(&format!(
            "retire {} · plus de beat `report` armé dans nika.yaml",
            unit(&dir, "report")
        )) && stdout.contains(&format!(
            "launchctl bootout gui/$UID/{}",
            unit(&dir, "report")
        )) && stdout.contains(&format!("supprimé {}", report.display())),
        "{stdout}"
    );
    assert!(!report.exists(), "the orphan's file is gone");
    assert!(doctor.exists(), "the declared beat keeps its unit");
}

/// Another project's unit is never retired, nor even named, when this
/// project retires its own orphan from the same unit directory.
#[test]
fn emit_write_never_retires_another_projects_unit() {
    let zone = machine_zone();
    let alpha = project("orphan-alpha", &two_beats_in(&zone));
    let beta = project("orphan-beta", &two_beats_in(&zone));
    let home = home(&alpha);
    for dir in [&alpha, &beta] {
        let out = arm(dir, &home, &["arm", "--emit", "launchd", "--write"]);
        assert_eq!(out.status.code(), Some(0), "{out:?}");
    }
    let agents = home.join("Library/LaunchAgents");
    let beta_report = agents.join(format!("{}.plist", unit(&beta, "report")));
    let before = std::fs::read_to_string(&beta_report).expect("beta's unit");
    std::fs::write(alpha.join("nika.yaml"), registry_in(&zone)).expect("alpha drops report");

    let out = arm(&alpha, &home, &["arm", "--emit", "launchd", "--write"]);

    let stdout = String::from_utf8_lossy(&out.stdout);
    assert_eq!(out.status.code(), Some(0), "{stdout}");
    assert!(
        !agents
            .join(format!("{}.plist", unit(&alpha, "report")))
            .exists(),
        "alpha's own orphan is retired"
    );
    assert_eq!(
        std::fs::read_to_string(&beta_report).expect("beta's unit stays"),
        before,
        "beta's unit is never touched"
    );
    assert!(
        !stdout.contains(&unit(&beta, "report")),
        "beta's unit is not even named: {stdout}"
    );
}

/// An edited cadence leaves the installed unit waking the old time: `nika
/// arm` names it stale with the re-emit that fixes it, and the re-emit makes
/// it current again. Before, the report said READY at the new time while
/// the unit kept waking the old one.
#[test]
fn the_report_names_a_unit_that_wakes_an_old_schedule() {
    let zone = machine_zone();
    let dir = project("stale-report", &registry_in(&zone));
    let home = home(&dir);
    let out = arm(&dir, &home, &["arm", "--emit", "systemd", "--write"]);
    assert_eq!(out.status.code(), Some(0), "{out:?}");
    let fresh = arm(&dir, &home, &["arm"]);
    assert!(
        !String::from_utf8_lossy(&fresh.stdout).contains("unités périmées"),
        "a unit just written is current"
    );

    let edited = registry_in(&zone).replace("0 3 * * *", "0 4 * * *");
    std::fs::write(dir.join("nika.yaml"), edited).expect("the cadence edited");
    let report = arm(&dir, &home, &["arm"]);
    let stdout = String::from_utf8_lossy(&report.stdout);
    let timer = home
        .join(".config/systemd/user")
        .join(format!("{}.timer", unit(&dir, "doctor")));
    assert!(
        stdout.contains("unités périmées")
            && stdout.contains(&timer.display().to_string())
            && stdout.contains("nika arm --emit systemd --write"),
        "{stdout}"
    );

    let out = arm(&dir, &home, &["arm", "--emit", "systemd", "--write"]);
    assert_eq!(out.status.code(), Some(0), "{out:?}");
    let current = arm(&dir, &home, &["arm"]);
    assert!(
        !String::from_utf8_lossy(&current.stdout).contains("unités périmées"),
        "re-emitted, the unit is current again"
    );
}
