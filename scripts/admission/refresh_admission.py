#!/usr/bin/env python3
# refresh_admission.py — the generated OpenRouter rows of inference-admission.toml, from bytes.
#
#   bash scripts/refresh-admission.sh                   # fetch public bytes, write the region
#   bash scripts/refresh-admission.sh --from DIR        # replay saved bytes (DIR/as_of.txt dates them)
#   bash scripts/refresh-admission.sh --check [--from DIR]   # write nothing, report drift
#   bash scripts/refresh-admission.sh --capacity [--from DIR] # windows and caps side by side
#   python3 scripts/admission/refresh_admission.py --selftest
#
# Exit 0 · the region matches its sources (or was written)
# Exit 2 · environment (a fetch failed · a file is unreadable or malformed)
# Exit 4 · drift under --check, or a route refused or absent from the catalogue (its old row is
#          kept verbatim and named, never dropped silently)
#
# The runtime never fetches a price: these rows are vendored. Each route of
# scripts/admission/sources.toml is read from OpenRouter's public endpoint listing, and the
# whole row follows from those bytes:
#   - rates: the peak per field over every endpoint and every override that can apply inside
#     the admitted context (OpenRouter may route a request to any endpoint, at any hour). The
#     input rate also covers a cache write: a paid reply's charge includes it, and the
#     full-context reservation must stay a worst case. An endpoint with no cache-read rate
#     may bill a cache hit as input, so the row then takes no discount.
#   - limits: the smallest context and max_completion_tokens over the endpoints. Under
#     context = "bound", a long-prompt override (min_prompt_tokens = T) is excluded by
#     admitting at most T - 1 input tokens.
#   - a priced axis the bounded text admission cannot meter (request, image, audio,
#     internal_reasoning...) refuses the route; web_search is a server tool it never sends.
#   - every endpoint states its own base prompt and completion price (zero is a price):
#     one without them refuses the route, so an absent price never reads as free and
#     never lowers a peak. A sparse override inherits whatever it does not name.
#   - a route whose every endpoint is free at every axis is declared free (0/0/0).
#   - a fractional peak rounds UP to whole nano-USD and says so.
#   - source = limits_source = the listing URL; both hashes are the sha256 of its bytes.
from __future__ import annotations

import argparse
import datetime
import difflib
import hashlib
import json
import pathlib
import sys
import tomllib
import urllib.error
import urllib.request
from decimal import ROUND_CEILING, Decimal

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCES = ROOT / "scripts/admission/sources.toml"
TARGET = ROOT / "crates/nika-catalog/data/inference-admission.toml"
SNAPSHOT = ROOT / "crates/nika-catalog/data/model-pricing.toml"
FIXTURES = ROOT / "scripts/admission/fixtures"
MODELS_URL = "https://openrouter.ai/api/v1/models"
BEGIN = "# BEGIN generated by scripts/refresh-admission.sh from scripts/admission/sources.toml"
END = "# END generated"
NANO = Decimal(10) ** 9
MAX_RATE = 9_007_199_254_740_991
METERED = ("prompt", "completion", "input_cache_read")
WRITES = ("input_cache_write", "input_cache_write_1h")
NOT_ADMITTED = ("web_search",)
NON_PRICE = ("discount", "overrides")
CONDITIONS = ("min_prompt_tokens", "utc_days", "utc_start", "utc_end")
HEADER = """\
# OpenRouter routes. A paid OpenRouter reply settles at its own reported
# `usage.cost` (non-BYOK, complete meters); these rows only reserve and admit
# the exact route. Each row is read from the saved
# GET /api/v1/models/<slug>/endpoints body that both hashes name: rates are the
# peak per field over every endpoint and every applicable override, the input
# rate also covering a cache write; limits are the smallest context and
# max_completion_tokens over the endpoints. The model is the public id from
# GET /api/v1/models, which the reply echoes, never the dated canonical slug.
# An endpoint `discount` is not assumed: the peak is the undiscounted price.
# A route free at every axis of every endpoint is declared free, for bounded
# text requests to that exact variant only: never inferred from a `:free`
# suffix, an absent price or a 0/0 snapshot row."""


class Refusal(Exception):
    """A route this law will not admit: named, and its old row kept."""


class Environment(Exception):
    """Bytes that could not be fetched or read."""


def file_name(model: str) -> str:
    return "endpoints/" + model.replace("/", "--").replace(":", "_") + ".json"


class Bytes:
    """Public bytes by deterministic name: fetched into a dated directory, or replayed."""

    def __init__(self, directory: pathlib.Path, fetch: bool) -> None:
        self.directory = directory
        self.fetch = fetch

    def get(self, name: str, url: str) -> bytes:
        path = self.directory / name
        if self.fetch:
            request = urllib.request.Request(url, headers={"user-agent": "nika-refresh-admission"})
            try:
                with urllib.request.urlopen(request, timeout=60) as response:
                    raw = response.read()
            except (urllib.error.URLError, TimeoutError) as error:
                raise Environment(f"fetch {url}: {error}") from error
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(raw)
            return raw
        try:
            return path.read_bytes()
        except OSError as error:
            raise Environment(f"read {path}: {error}") from error

    def as_of(self) -> str:
        if self.fetch:
            day = datetime.datetime.now(datetime.timezone.utc).date().isoformat()
            self.directory.mkdir(parents=True, exist_ok=True)
            (self.directory / "as_of.txt").write_text(day + "\n", encoding="utf-8")
            return day
        try:
            day = (self.directory / "as_of.txt").read_text(encoding="utf-8").strip()
        except OSError as error:
            raise Environment(f"read {self.directory}/as_of.txt: {error}") from error
        datetime.date.fromisoformat(day)
        return day


def nano(value) -> Decimal:
    return Decimal(str(value)) * NANO


def whole(rate: Decimal, field: str, notes: list[str]) -> int:
    if rate == rate.to_integral_value():
        return int(rate)
    notes.append(f"{field} peak {rate.normalize()} rounded up")
    return int(rate.to_integral_value(rounding=ROUND_CEILING))


def endpoints_url(model: str, listing: dict) -> str:
    """A variant (`:free`) shares its paid slug's details link, so it is named by its id."""
    if ":" in model:
        return f"{MODELS_URL}/{model}/endpoints"
    return "https://openrouter.ai" + listing["links"]["details"]


def stated(value) -> bool:
    """A base price the listing states: a finite, non-negative number. Zero is a price."""
    try:
        rate = Decimal(str(value))
    except ArithmeticError:
        return False
    return value is not None and rate.is_finite() and rate >= 0


def peaks(model: str, endpoints: list, context_policy: str):
    """Every rate the route can bill inside its admitted context, its long-prompt
    threshold, the notes a reader needs, and whether any endpoint lacks a cache-read rate.
    Each endpoint's base pricing must state its prompt and completion price first."""
    rates = {field: [] for field in METERED + WRITES}
    threshold, notes, uncached = None, [], False
    for endpoint in endpoints:
        prices = endpoint.get("pricing")
        if not isinstance(prices, dict):
            raise Refusal(f"{model}: no pricing on {endpoint.get('tag')}")
        for field in ("prompt", "completion"):
            if not stated(prices.get(field)):
                raise Refusal(f"{model}: no {field} price on {endpoint.get('tag')}")
        for key, value in prices.items():
            if key in METERED or key in WRITES or key in NON_PRICE:
                continue
            if key in NOT_ADMITTED:
                if f"{key} not admitted" not in notes:
                    notes.append(f"{key} not admitted")
                continue
            if Decimal(str(value)) != 0:
                raise Refusal(f"{model}: unmetered priced axis {key} on {endpoint.get('tag')}")
        uncached = uncached or "input_cache_read" not in prices
        applicable = [prices]
        for override in prices.get("overrides") or []:
            unknown = set(override) - set(METERED + WRITES + NOT_ADMITTED + CONDITIONS)
            if unknown:
                raise Refusal(f"{model}: unknown override key {sorted(unknown)[0]}")
            if "min_prompt_tokens" in override:
                start = int(override["min_prompt_tokens"])
                threshold = start if threshold is None else min(threshold, start)
                if context_policy == "bound":
                    continue
                if "long-prompt override in the peak" not in notes:
                    notes.append("long-prompt override in the peak")
            elif "time windows in the peak" not in notes:
                notes.append("time windows in the peak")
            applicable.append(override)
        for prices_set in applicable:
            for field in METERED + WRITES:
                if field in prices_set:
                    rates[field].append(nano(prices_set[field]))
    return rates, threshold, notes, uncached


def build(route: dict, listing: dict, raw: bytes, url: str, config: dict, as_of: str) -> str:
    model = route["model"]
    try:
        document = json.loads(raw)["data"]
    except (ValueError, KeyError, TypeError) as error:
        raise Refusal(f"{model}: unreadable endpoint listing ({error})") from error
    if document.get("id") != model:
        raise Refusal(f"{model}: the listing names {document.get('id')}")
    endpoints = document.get("endpoints") or []
    if not endpoints:
        raise Refusal(f"{model}: no endpoint listed")
    context = min(int(e["context_length"]) for e in endpoints)
    output = min(int(e["max_completion_tokens"]) for e in endpoints)
    rates, threshold, notes, uncached = peaks(model, endpoints, route["context"])
    if not rates["prompt"] or not rates["completion"]:
        raise Refusal(f"{model}: a prompt or completion price is missing")
    if threshold is not None and route["context"] == "bound" and threshold - 1 < context:
        context = threshold - 1
        notes.append(f"long-prompt override from {threshold} excluded")
    prompt = max(rates["prompt"])
    write = max(rates["input_cache_write"] + rates["input_cache_write_1h"], default=Decimal(0))
    if write > prompt:
        notes.append("input rate is the cache-write peak")
    input_rate = whole(max(prompt, write), "input", notes)
    output_rate = whole(max(rates["completion"]), "output", notes)
    if uncached or not rates["input_cache_read"]:
        cached = input_rate
        if input_rate:
            notes.append("an endpoint has no cache-read rate: no discount")
    else:
        cached = whole(max(rates["input_cache_read"]), "cache read", notes)
    free = input_rate == output_rate == cached == 0
    if not free and min(input_rate, output_rate, cached) <= 0:
        raise Refusal(f"{model}: partly free rates are neither a peak nor a declaration")
    if cached > input_rate or max(input_rate, output_rate, cached) > MAX_RATE:
        raise Refusal(f"{model}: rates outside the tariff invariants")
    if context <= 0 or not 0 < output < 2**32:
        raise Refusal(f"{model}: limits outside the tariff invariants")
    digest = hashlib.sha256(raw).hexdigest()
    plural = "endpoint" if len(endpoints) == 1 else "endpoints"
    lines = [f"# {model}: {len(endpoints)} {plural}" + "".join(f"; {n}" for n in notes) + "."]
    lines.append("[[tariffs]]")
    for key, value in (
        ("provider", "openrouter"),
        ("billing_provider", "openrouter"),
        ("currency", "USD"),
        ("output_token_param", "max_tokens"),
        ("model", model),
    ):
        lines.append(f'{key} = "{value}"')
    lines.append(f'endpoints = ["{config["endpoint"]}"]')
    for key, value in (
        ("source", url),
        ("limits_source", url),
        ("route_source", config["route_source"]),
        ("as_of", as_of),
        ("source_sha256", digest),
        ("limits_sha256", digest),
    ):
        lines.append(f'{key} = "{value}"')
    lines.append(f"context_tokens = {context}")
    lines.append(f"max_output_tokens = {output}")
    if free:
        lines.append("declared_free = true")
    lines.append(f"input_nano_per_token = {input_rate}")
    lines.append(f"output_nano_per_token = {output_rate}")
    lines.append(f"cached_nano_per_token = {cached}")
    return "\n".join(lines)


def split_region(text: str):
    """(before, region body, after), or None when the markers are absent."""
    lines = text.split("\n")
    try:
        start = next(i for i, line in enumerate(lines) if line.startswith(BEGIN))
        end = next(i for i, line in enumerate(lines) if i > start and line == END)
    except StopIteration:
        return None
    return "\n".join(lines[: start + 1]), "\n".join(lines[start + 1 : end]), "\n".join(lines[end:])


def kept_rows(body: str) -> dict:
    """The current region's rows by model, so a refused route keeps its row verbatim."""
    rows = {}
    for block in body.split("\n\n"):
        for line in block.split("\n"):
            if line.startswith('model = "'):
                rows[line[len('model = "') : -1]] = block.strip("\n")
    return rows


def generate(source: Bytes, config: dict, current: dict):
    """The region body and the named routes whose old rows were kept."""
    as_of = source.as_of()
    try:
        catalogue = {m["id"]: m for m in json.loads(source.get("models.json", MODELS_URL))["data"]}
    except (ValueError, KeyError, TypeError) as error:
        raise Environment(f"models.json: {error}") from error
    rows, kept = [], []
    for route in config["routes"]:
        model = route["model"]
        if route.get("context", "bound") not in ("bound", "full"):
            raise Environment(f"{model}: context must be bound or full")
        route = {"model": model, "context": route.get("context", "bound")}
        try:
            listing = catalogue.get(model)
            if listing is None:
                raise Refusal(f"{model}: absent from the catalogue")
            url = endpoints_url(model, listing)
            rows.append(build(route, listing, source.get(file_name(model), url), url, config, as_of))
        except Refusal as why:
            kept.append(str(why))
            if model in current:
                rows.append(current[model])
    return HEADER + "\n\n" + "\n\n".join(rows) + "\n", kept


def capacity(source: Bytes) -> None:
    """Every admitted route's window and cap beside the snapshot's exact row and the live
    list. The admitted pair is a deliberate bound with its own source and date; a snapshot
    window that disagrees with the live list is reported, never merged."""
    tariffs = tomllib.loads(TARGET.read_text(encoding="utf-8"))["tariffs"]
    snapshot = {
        (r["provider"], r["model_pattern"]): r
        for r in tomllib.loads(SNAPSHOT.read_text(encoding="utf-8"))["rules"]
    }
    catalogue = {m["id"]: m for m in json.loads(source.get("models.json", MODELS_URL))["data"]}
    for row in tariffs:
        snap = snapshot.get((row["provider"], row["model"]))
        live = catalogue.get(row["model"]) if row["provider"] == "openrouter" else None
        snap_pair = None if snap is None else [snap.get("context_window_tokens"), snap.get("max_output_tokens")]
        live_pair = None
        if live is not None:
            live_pair = [live.get("context_length"), (live.get("top_provider") or {}).get("max_completion_tokens")]
        mark = "DISAGREE" if snap_pair and live_pair and snap_pair[0] != live_pair[0] else "ok"
        print(
            f"{mark:8} {row['provider']}/{row['model']}: admitted "
            f"{row['context_tokens']}/{row['max_output_tokens']} ({row['limits_source']}, "
            f"{row['as_of']}); snapshot {snap_pair}; live {live_pair}"
        )


def run(arguments) -> int:
    config = tomllib.loads(SOURCES.read_text(encoding="utf-8"))
    if config.get("schema") != "nika/admission-sources@1":
        raise Environment("scripts/admission/sources.toml: unknown schema")
    if arguments.source:
        source = Bytes(pathlib.Path(arguments.source), fetch=False)
    else:
        day = datetime.datetime.now(datetime.timezone.utc).date().isoformat()
        source = Bytes(ROOT / "target/admission-sources" / day, fetch=True)
    if arguments.capacity:
        capacity(source)
        return 0
    text = TARGET.read_text(encoding="utf-8")
    parts = split_region(text)
    if parts is None:
        raise Environment(f"{TARGET.name}: the generated region markers are missing")
    before, body, after = parts
    region, kept = generate(source, config, kept_rows(body))
    for why in kept:
        print(f"REFUSED (old row kept, if any): {why}", file=sys.stderr)
    if region.rstrip("\n") == body.rstrip("\n"):
        print(f"{TARGET.name}: the generated region matches its sources")
        return 4 if kept else 0
    if arguments.check:
        diff = difflib.unified_diff(body.split("\n"), region.rstrip("\n").split("\n"), "current", "sources", lineterm="")
        print("\n".join(diff))
        return 4
    TARGET.write_text(before + "\n" + region + after, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}: {len(config['routes'])} route(s), {len(kept)} kept")
    return 4 if kept else 0


def selftest() -> int:
    """Synthetic listings with a golden region: the laws' teeth, offline."""
    config = tomllib.loads((FIXTURES / "sources.toml").read_text(encoding="utf-8"))
    source = Bytes(FIXTURES, fetch=False)
    stale = kept_rows((FIXTURES / "kept-row.toml").read_text(encoding="utf-8"))
    region, kept = generate(source, config, stale)
    expected = (FIXTURES / "expected-region.toml").read_text(encoding="utf-8")
    failures = []
    if region != expected:
        diff = difflib.unified_diff(expected.split("\n"), region.split("\n"), "golden", "generated", lineterm="")
        failures.append("region differs from the golden:\n" + "\n".join(diff))
    wanted = {"vendor/metered-image: unmetered priced axis image on vendor-a",
              "vendor/vanished: absent from the catalogue",
              "vendor/zero-unpriced: no pricing on vendor-b",
              "vendor/zero-axisless: no completion price on vendor-b"}
    if set(kept) != wanted:
        failures.append(f"refusals {sorted(kept)} != {sorted(wanted)}")
    for failure in failures:
        print(f"SELFTEST FAIL: {failure}", file=sys.stderr)
    if not failures:
        print("selftest: golden region and named refusals reproduced")
    return 1 if failures else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--from", dest="source", help="replay saved bytes from this directory")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 4 on drift")
    parser.add_argument("--capacity", action="store_true", help="report windows and caps")
    parser.add_argument("--selftest", action="store_true", help="prove the laws offline")
    arguments = parser.parse_args()
    if arguments.selftest:
        return selftest()
    try:
        return run(arguments)
    except Environment as error:
        print(f"ENVIRONMENT: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
